<?php

/*
|--------------------------------------------------------------------------
| Push notifications (P5, docs/notifications.md)
|--------------------------------------------------------------------------
| Web Push (VAPID) for the staff dashboard, and a stub for FCM (a later mobile app). The VAPID keys are generated by
| `php artisan chat:bootstrap-secrets` into `.env`; with either of them missing the whole feature is off (no `push` shared prop,
| no subscription endpoints that work, listeners do nothing) and the dashboard falls back to in-tab toast + sound + title badge.
*/
return [

    /*
     * VAPID: the application server key pair (never rotate it casually: every browser subscription is bound to the public key, and a
     * changed key makes the client subscribe again). `subject` identifies the sender to the push services: a `mailto:` address or an
     * https URL; it defaults to the app URL.
     */
    'vapid' => [
        'public_key' => env('VAPID_PUBLIC_KEY'),
        'private_key' => env('VAPID_PRIVATE_KEY'),
        'subject' => env('VAPID_SUBJECT'),
    ],

    /* Web Push delivery. `timeout`: seconds per request to a push service; redirects are never followed. */
    'web' => [
        'timeout' => 10,
    ],

    /* FCM (a future mobile app): a stub that only logs while `enabled` is false; nothing is sent over the network either way. */
    'fcm' => [
        'enabled' => (bool) env('PUSH_FCM_ENABLED', false),
    ],

    /* The queue the push jobs run on (null = the default queue). */
    'queue' => env('PUSH_QUEUE'),

    /* Tries / pauses (seconds) of one push job: a push service that answers 5xx or times out is retried, 404/410 never. */
    'job' => [
        'tries' => 3,
        'backoff' => [5, 30],
    ],

    /*
     * Who is "looking at the dashboard": a heartbeat from an open dashboard younger than this means the agent gets the in-page
     * toast + sound (and a page notification when the tab is in the background), not an OS push.
     */
    'visible_window_seconds' => 60,

    /* The most characters of the first / latest visitor message that go into a notification body (when previews are on). */
    'preview_max_length' => 120,

    /* How long (seconds) a push service keeps a "new message" for a device that is offline; an older message is not worth waking a phone for. */
    'message_ttl_seconds' => 900,

    /* A visitor who sends several messages in a row notifies the agent at most once per this many seconds per chat. */
    'message_throttle_seconds' => 8,

    /* How long the "who was pushed this chat" markers (used to send the silent dismiss) live: longer than any offer. */
    'ledger_ttl_seconds' => 3600,

    /* "Not now" on the first-login dialog hides it for this many days. */
    'snooze_days' => 7,

    /* Browsers / devices a member of staff may register (the oldest is replaced beyond it). */
    'max_subscriptions_per_user' => 10,
    'max_devices_per_user' => 10,

    /* Per minute and staff member: `POST /me/push-subscriptions/test` (each call is a real push to the push services). */
    'rate_limits' => [
        'test_per_minute' => 3,
        'subscriptions_per_minute' => 20,
    ],
];
